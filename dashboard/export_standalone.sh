#!/usr/bin/env bash
# Export the dashboard as a standalone repo (app at root) for Streamlit Cloud.
# The exports are small committed Parquet, so the serving set is bundled
# into the export and the app needs no credentials. Re-run + push the
# standalone repo to refresh data.
# Usage: ./dashboard/export_standalone.sh /path/to/ticket-dashboard-checkout
set -euo pipefail
DEST="${1:?usage: export_standalone.sh <destination-dir>}"
mkdir -p "$DEST/.streamlit" "$DEST/data_warehouse/semantic" "$DEST/data_warehouse/gold" "$DEST/data_warehouse/silver"
cp dashboard/streamlit_app.py dashboard/data.py dashboard/requirements.txt "$DEST/"
cp dashboard/.streamlit/secrets.toml.example dashboard/.streamlit/config.toml "$DEST/.streamlit/"
cp data/data_warehouse/semantic/*.parquet "$DEST/data_warehouse/semantic/"
cp data/data_warehouse/gold/analytics_tickets_price_changes.parquet "$DEST/data_warehouse/gold/"
cp data/data_warehouse/silver/fct_tickets_listings_latest.parquet "$DEST/data_warehouse/silver/"
cat > "$DEST/README.md" <<'MD'
# FIFA 2026 Ticket Tracker (standalone dashboard)

Streamlit dashboard over the ticket-scraper semantic layer. Reads the
bundled published Parquet exports in `data_warehouse/`; no secrets needed.
Generated by `dashboard/export_standalone.sh` in the ticket-scraper repo —
do not edit by hand; re-export to refresh.

Deploy: Streamlit Community Cloud -> main file `streamlit_app.py`.
MD
cat > "$DEST/.gitignore" <<'GI'
.streamlit/secrets.toml
__pycache__/
GI
echo "Exported standalone dashboard to $DEST"
